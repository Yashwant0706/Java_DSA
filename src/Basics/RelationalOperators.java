package Basics;

public class RelationalOperators {
    static void main(String args[]) {

        // gives the answer in true-False form
        int a = 3;
        int b = 5;

        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>-b);
        System.out.println(a<=b);
    }
}
